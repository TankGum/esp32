#!/usr/bin/env python3
"""Turns Be Vietnam Pro (tools/fonts, SIL OFL) into anti-aliased bitmap fonts for the firmware.

Each glyph is stored as 4-bit coverage (two pixels per byte), so text can be blended onto any
background. Output: include/ui_fonts.h. Run again after changing the sizes or the character set:
    python3 tools/gen_fonts.py
"""
import os
from PIL import ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VI = ("àáảãạăằắẳẵặâầấẩẫậèéẻẽẹêềếểễệìíỉĩịòóỏõọôồốổỗộơờớởỡợùúủũụưừứửữựỳýỷỹỵđ"
      "ÀÁẢÃẠĂẰẮẲẴẶÂẦẤẨẪẬÈÉẺẼẸÊỀẾỂỄỆÌÍỈĨỊÒÓỎÕỌÔỒỐỔỖỘƠỜỚỞỠỢÙÚỦŨỤƯỪỨỬỮỰỲÝỶỸỴĐ")
FULL = "".join(chr(c) for c in range(32, 127)) + VI + "°›‹•…–—“”‘’·×"
DIGITS = "0123456789:. -+%°/"
FONTS = [  # name, weight, pixel size, characters
    ("ui12", "Medium", 12, FULL),
    ("ui13b", "SemiBold", 13, FULL),
    ("ui15", "Medium", 15, FULL),
    ("ui15b", "SemiBold", 15, FULL),
    ("ui20b", "Bold", 20, FULL),
    ("num34", "SemiBold", 34, DIGITS + "dBkmhKMs"),
    ("num68", "Regular", 68, DIGITS),
]

def build(name, weight, size, chars):
    font = ImageFont.truetype(os.path.join(ROOT, "tools/fonts", f"BeVietnamPro-{weight}.ttf"), size)
    glyphs, bits = [], bytearray()
    for ch in sorted(set(chars)):
        adv = round(font.getlength(ch))
        mask, (ox, oy) = font.getmask2(ch, mode="L", anchor="ls")
        w, h = mask.size
        if ch == " " or w == 0 or h == 0:
            w = h = 0
        px = [mask.getpixel((x, y)) if w else 0 for y in range(h) for x in range(w)]
        offset = len(bits)
        nib = [(v * 15 + 127) // 255 for v in px]
        if len(nib) % 2: nib.append(0)
        for i in range(0, len(nib), 2): bits.append(nib[i] << 4 | nib[i + 1])
        glyphs.append((ord(ch), offset, w, h, ox, oy, adv))
    out = [f"static const uint8_t {name}_bits[] PROGMEM = {{"]
    for i in range(0, len(bits), 24):
        out.append("    " + ",".join(str(b) for b in bits[i:i + 24]) + ",")
    out.append("};")
    out.append(f"static const AAGlyph {name}_glyphs[] PROGMEM = {{")
    for g in glyphs:
        out.append("    {%d, %d, %d, %d, %d, %d, %d}," % g)
    out.append("};")
    # The real extent of the set (Vietnamese capitals stack accents above the font's ascent),
    # so a box of ascent + descent never clips a glyph.
    ascent = max(-g[5] for g in glyphs if g[3])
    descent = max(0, max(g[5] + g[3] for g in glyphs if g[3]))
    out.append(f"static const AAFont {name} = {{{name}_glyphs, {len(glyphs)}, {name}_bits, {ascent}, {descent}}};")
    return "\n".join(out), len(bits)

parts = ["""#pragma once
// Generated by tools/gen_fonts.py from Be Vietnam Pro (SIL Open Font License, tools/fonts/OFL.txt).
// Do not edit by hand.
#include <Arduino.h>

struct AAGlyph {
    uint32_t code;   // Unicode code point, glyphs are sorted by it
    uint32_t offset; // into the font's bits, 4-bit coverage, two pixels per byte, row by row
    uint8_t w, h;
    int8_t dx, dy;   // top-left of the bitmap relative to the pen on the baseline
    uint8_t adv;
};
struct AAFont {
    const AAGlyph *glyphs;
    uint16_t count;
    const uint8_t *bits;
    uint8_t ascent, descent;
};
"""]
total = 0
for f in FONTS:
    src, n = build(*f)
    parts.append(src)
    total += n
open(os.path.join(ROOT, "include/ui_fonts.h"), "w").write("\n".join(parts) + "\n")
print(f"include/ui_fonts.h: {len(FONTS)} fonts, {total} bytes of glyph data")
